-- =====================================================================
-- Stock4event - Schema PostgreSQL (baseline)
-- Equivalente ao DDL que o Hibernate (ddl-auto=update) gera a partir das
-- entidades JPA do Stock4event-BackEnd. Gerado por leitura das entidades.
-- Ordem: tabelas-pai antes das filhas.
-- =====================================================================

CREATE TABLE perfis (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(50)  NOT NULL UNIQUE,
    descricao  VARCHAR(200)
);

CREATE TABLE empresas (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(150) NOT NULL,
    cnpj       VARCHAR(18)  NOT NULL UNIQUE,
    telefone   VARCHAR(20),
    tipo       VARCHAR(20),               -- CLIENTE | DISTRIBUIDOR | AMBOS (legado: COMPRADOR, INATIVO)
    descricao  VARCHAR(300),
    logo_url   VARCHAR(500),
    capa_url   VARCHAR(500),
    criado_em  TIMESTAMP(6)
);

CREATE TABLE usuarios (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100) NOT NULL,
    email       VARCHAR(150) NOT NULL UNIQUE,
    senha_hash  VARCHAR(255) NOT NULL,
    perfil_id   BIGINT  NOT NULL REFERENCES perfis(id),
    empresa_id  BIGINT  NOT NULL REFERENCES empresas(id),
    ativo       INTEGER NOT NULL,
    perfil_uso  VARCHAR(30),
    cpf         VARCHAR(14),
    foto_url    VARCHAR(500),
    criado_em   TIMESTAMP(6)
);

CREATE TABLE produtos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id     BIGINT        NOT NULL REFERENCES empresas(id),
    nome           VARCHAR(300)  NOT NULL,
    preco_venda    NUMERIC(10,2) NOT NULL,
    unidade        VARCHAR(20)   NOT NULL,
    descricao      VARCHAR(500),
    imagem_url     VARCHAR(500),
    ativo          INTEGER       NOT NULL,
    estoque        NUMERIC(10,3),
    codigo         VARCHAR(40)   NOT NULL UNIQUE,
    codigo_origem  VARCHAR(40),
    criado_em      TIMESTAMP(6)                  -- quando o produto foi cadastrado
);

CREATE TABLE eventos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id   BIGINT       NOT NULL REFERENCES empresas(id),
    nome         VARCHAR(150) NOT NULL,
    data_inicio  DATE         NOT NULL,
    data_fim     DATE         NOT NULL,
    status       VARCHAR(20)  NOT NULL
);

CREATE TABLE barracas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id       BIGINT       NOT NULL REFERENCES eventos(id),
    nome            VARCHAR(100) NOT NULL,
    responsavel_id  BIGINT       NOT NULL REFERENCES usuarios(id),
    ativa           INTEGER      NOT NULL
);

CREATE TABLE estoque_barraca (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barraca_id     BIGINT        NOT NULL REFERENCES barracas(id),
    produto_id     BIGINT        NOT NULL REFERENCES produtos(id),
    quantidade     NUMERIC(10,3) NOT NULL,
    atualizado_em  TIMESTAMP(6),
    CONSTRAINT uk_estoque_barraca_barraca_produto UNIQUE (barraca_id, produto_id)
);

CREATE TABLE enderecos_entrega (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresas(id),
    apelido     VARCHAR(80)  NOT NULL,
    logradouro  VARCHAR(150) NOT NULL,
    numero      VARCHAR(20)  NOT NULL,
    complemento VARCHAR(80),
    bairro      VARCHAR(80)  NOT NULL,
    cidade      VARCHAR(80)  NOT NULL,
    uf          VARCHAR(2)   NOT NULL,
    cep         VARCHAR(9)   NOT NULL,
    principal   BOOLEAN      NOT NULL,
    latitude    DOUBLE PRECISION,             -- reservado para cálculo de distância
    longitude   DOUBLE PRECISION
);

CREATE TABLE pedido (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                    VARCHAR(20)   NOT NULL,           -- pdv | marketplace
    barraca_id              BIGINT REFERENCES barracas(id),
    operador_id             BIGINT        NOT NULL REFERENCES usuarios(id),
    empresa_compradora_id   BIGINT REFERENCES empresas(id),
    empresa_fornecedora_id  BIGINT REFERENCES empresas(id),
    endereco_entrega_id     BIGINT REFERENCES enderecos_entrega(id),
    endereco_resumo         VARCHAR(300),
    cep                     VARCHAR(9),
    logradouro              VARCHAR(150),
    numero                  VARCHAR(20),
    complemento             VARCHAR(80),
    bairro                  VARCHAR(80),
    cidade                  VARCHAR(80),
    uf                      VARCHAR(2),
    metodo_pagamento        VARCHAR(20),
    taxa_entrega            NUMERIC(10,2),
    observacao              VARCHAR(500),
    valor_total             NUMERIC(10,2) NOT NULL,
    status                  VARCHAR(20)   NOT NULL,
    criado_em               TIMESTAMP(6),
    chave_venda             VARCHAR(64) UNIQUE,      -- PDV: idempotência da venda
    valor_recebido          NUMERIC(10,2),           -- PDV: dinheiro entregue
    troco                   NUMERIC(10,2),           -- PDV: calculado pelo servidor
    cliente_nome            VARCHAR(100),            -- PDV: cliente opcional
    cliente_documento       VARCHAR(14)              -- PDV: CPF/CNPJ opcional (dígitos)
);

CREATE TABLE itens_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT        NOT NULL REFERENCES pedido(id),
    produto_id      BIGINT        NOT NULL REFERENCES produtos(id),
    quantidade      NUMERIC(10,3) NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL
);

CREATE TABLE pagamentos (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id             BIGINT        NOT NULL REFERENCES pedido(id),
    metodo                VARCHAR(20)   NOT NULL,
    valor                 NUMERIC(10,2) NOT NULL,
    status                VARCHAR(20)   NOT NULL,
    referencia_pagamento  VARCHAR(120)
);

CREATE TABLE solicitacoes_compra (
    id                           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_compradora_id        BIGINT        NOT NULL REFERENCES empresas(id),
    empresa_fornecedora_id       BIGINT        NOT NULL REFERENCES empresas(id),
    usuario_solicitante_id       BIGINT        NOT NULL REFERENCES usuarios(id),
    pedido_id                    BIGINT REFERENCES pedido(id),
    valor_total                  NUMERIC(10,2) NOT NULL,
    status                       VARCHAR(20)   NOT NULL,
    observacao                   VARCHAR(500),
    metodo_pagamento             VARCHAR(20),
    endereco_resumo              VARCHAR(300),
    cep                          VARCHAR(9),
    logradouro                   VARCHAR(150),
    numero                       VARCHAR(20),
    complemento                  VARCHAR(80),
    bairro                       VARCHAR(80),
    cidade                       VARCHAR(80),
    uf                           VARCHAR(2),
    taxa_entrega                 NUMERIC(10,2),
    estoque_comprador_creditado  BOOLEAN       NOT NULL,
    criado_em                    TIMESTAMP(6)
);

CREATE TABLE itens_solicitacao_compra (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id  BIGINT        NOT NULL REFERENCES solicitacoes_compra(id),
    produto_id      BIGINT        NOT NULL REFERENCES produtos(id),
    quantidade      NUMERIC(10,3) NOT NULL,
    preco_unitario  NUMERIC(10,2) NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL
);

CREATE TABLE caminhoneiros (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT       NOT NULL REFERENCES empresas(id),
    nome        VARCHAR(120) NOT NULL,
    veiculo     VARCHAR(80)  NOT NULL,
    rota        VARCHAR(150) NOT NULL,
    status      VARCHAR(30)  NOT NULL,
    criado_em   TIMESTAMP(6)
);

CREATE TABLE entregas_logistica (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    caminhoneiro_id  BIGINT       NOT NULL REFERENCES caminhoneiros(id),
    nome_cliente     VARCHAR(120) NOT NULL,
    cidade           VARCHAR(80)  NOT NULL,
    rota             VARCHAR(150) NOT NULL,
    status           VARCHAR(30)  NOT NULL,
    criado_em        TIMESTAMP(6)
);

CREATE TABLE cartoes_pagamento_salvos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id        BIGINT      NOT NULL REFERENCES empresas(id),
    tipo              VARCHAR(20) NOT NULL,
    apelido           VARCHAR(80),
    bandeira          VARCHAR(40) NOT NULL,
    ultimos_digitos   VARCHAR(4)  NOT NULL,
    numero_mascarado  VARCHAR(24) NOT NULL,
    validade          VARCHAR(5)  NOT NULL,
    titular           VARCHAR(120) NOT NULL,
    criado_em         TIMESTAMP(6)
);

CREATE TABLE chaves_pix_salvas (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id       BIGINT      NOT NULL REFERENCES empresas(id),
    apelido          VARCHAR(80) NOT NULL,
    tipo_chave       VARCHAR(20) NOT NULL,
    chave_mascarada  VARCHAR(60) NOT NULL,
    ultimos_digitos  VARCHAR(4)  NOT NULL,
    criado_em        TIMESTAMP(6)
);

CREATE TABLE formas_pagamento_salvas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id  BIGINT      NOT NULL REFERENCES empresas(id),
    tipo        VARCHAR(20) NOT NULL,
    apelido     VARCHAR(80) NOT NULL,
    principal   BOOLEAN     NOT NULL
);

-- E-mail de boas-vindas: um registro por conta (usuario_id único) com o resultado do envio.
-- Gravado na mesma transação do cadastro; o backend envia e refaz falhas temporárias.
CREATE TABLE email_boas_vindas (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT       NOT NULL UNIQUE,
    destinatario          VARCHAR(150) NOT NULL,
    nome_destinatario     VARCHAR(100),
    tipo                  VARCHAR(20)  NOT NULL,
    status                VARCHAR(20)  NOT NULL,
    tentativas            INTEGER      NOT NULL,
    ultimo_erro           VARCHAR(500),
    proxima_tentativa_em  TIMESTAMP(6) NOT NULL,
    criado_em             TIMESTAMP(6) NOT NULL,
    atualizado_em         TIMESTAMP(6) NOT NULL,
    enviado_em            TIMESTAMP(6)
);
